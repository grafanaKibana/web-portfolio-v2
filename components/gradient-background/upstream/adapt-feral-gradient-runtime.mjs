/** Writes the adapted runtime and prints reproducibility hashes. */
async function main() {
  const sourcePath = resolve(process.argv[2] ?? DEFAULT_SOURCE);
  const destinationPath = resolve(process.argv[3] ?? DEFAULT_DESTINATION);
  const sourceBuffer = await readFile(sourcePath);
  const source = sourcePath.endsWith(".gz")
    ? gunzipSync(sourceBuffer).toString("utf8")
    : sourceBuffer.toString("utf8");
  const output = adaptFeralGradientRuntime(source);
  await writeFile(destinationPath, output);
  process.stdout.write(
    `${destinationPath}\nsource ${sha256(source)}\nadapted ${sha256(output)}\n`,
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  void main().catch((error) => {
    process.stderr.write(`${error instanceof Error ? error.message : error}\n`);
    process.exitCode = 1;
  });
}
